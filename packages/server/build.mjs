// Bundles the edge function for Supabase's Deno runtime, and the scheduled file sweep for Node.
// Workspace code (@car/core) is inlined;
// npm packages stay imports, rewritten to Deno's `npm:` specifiers at the versions installed here
// so the deployed function runs the same code the tests ran.
import { build } from 'esbuild'
import { readFileSync } from 'node:fs'
import { createRequire } from 'node:module'

const require = createRequire(import.meta.url)
const EXTERNAL = ['@anthropic-ai/sdk', '@supabase/supabase-js']

const versionOf = (name) => {
  const main = require.resolve(name)
  const root = main.slice(
    0,
    main.lastIndexOf(`/node_modules/${name}/`) + `/node_modules/${name}`.length,
  )
  return JSON.parse(readFileSync(`${root}/package.json`, 'utf8')).version
}

const npmSpecifiers = {
  name: 'npm-specifiers',
  setup(b) {
    const filter = new RegExp(`^(${EXTERNAL.map((n) => n.replace('/', '\\/')).join('|')})(/.*)?$`)
    b.onResolve({ filter }, ({ path }) => {
      const name = EXTERNAL.find((n) => path === n || path.startsWith(`${n}/`))
      return { path: `npm:${name}@${versionOf(name)}${path.slice(name.length)}`, external: true }
    })
  },
}

await build({
  entryPoints: ['src/main.ts'],
  outfile: '../../supabase/functions/assistant/index.js',
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  target: 'es2022',
  plugins: [npmSpecifiers],
  banner: {
    js: '// Generated by `pnpm --filter @car/server build` from packages/server. Do not edit.',
  },
  logLevel: 'info',
})

// Runs in GitHub Actions on Node and only uses fetch, so it needs no npm packages.
await build({
  entryPoints: ['src/sweepMain.ts'],
  outfile: 'dist/sweep-files.mjs',
  bundle: true,
  format: 'esm',
  platform: 'node',
  target: 'node24',
  logLevel: 'info',
})
